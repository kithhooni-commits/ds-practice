def _key(run):
    """서식 지문. 이게 같으면 붙여도 보이는 결과가 달라지지 않는다."""
    f = run.font
    try:
        rgb = f.color.rgb
    except Exception:
        rgb = None
    return (f.name, f.size, f.bold, f.italic, rgb)


def merge_runs(para) -> None:
    """서식이 같은 인접 run 을 합친다.

    파워포인트는 맞춤법 검사 등으로 한 문장을 여러 run 으로 쪼개 둔다. 그러면
    문장 단위 치환이 안 걸린다. 서식이 **같은** 것끼리만 붙이므로 부분 굵게는
    그대로 남는다.
    """
    runs = list(para.runs)
    i = 0
    while i < len(runs) - 1:
        a, b = runs[i], runs[i + 1]
        if _key(a) == _key(b):
            a.text = a.text + b.text
            b._r.getparent().remove(b._r)
            runs.pop(i + 1)
        else:
            i += 1


def iter_paras(slide):
    for sh in slide.shapes:
        if sh.has_text_frame:
            yield from sh.text_frame.paragraphs
        if sh.has_table:
            for row in sh.table.rows:
                for cell in row.cells:
                    yield from cell.text_frame.paragraphs


